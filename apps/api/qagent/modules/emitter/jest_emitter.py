"""Render generated cases as Jest files (CLAUDE.md section 8, agent 3).

The pytest emitter's sibling, for the projects section 8 means by "Jest
depending on project type": a Node repository whose developers will not keep a
Python test suite around. Same input (the generator's declarative documents),
same grouping (one file per API module), same promise: the output depends on
nothing from QAgent. It needs Jest and Node 18+ (for the built-in ``fetch``),
and nothing else - no axios, no supertest.

Values reach the output only through ``json.dumps(..., ensure_ascii=True)``.
JSON is a subset of JavaScript expression syntax once U+2028/U+2029 are
escaped, which ``ensure_ascii`` guarantees, so a spec value can only ever
become a literal: a path of ``/x"); require("child_process")...`` renders as a
harmless string.

The one duplicated piece of logic is GraphQL error classification, which has
to exist in JavaScript for the emitted suite to run. ``_GRAPHQL_HELPERS`` is a
port of ``modules/graphql/errors.py``, and ``tests/test_jest_emitter.py`` runs
both over the same table of responses so the two cannot quietly disagree.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

from qagent.modules.emitter.pytest_emitter import EmissionReport, EmittedFile, module_name_for
from qagent.modules.generator.rules import GeneratedCase

logger = logging.getLogger(__name__)


def _js(value: object) -> str:
    """A JavaScript literal for a JSON-able value - never raw text."""
    return json.dumps(value, ensure_ascii=True)


_MODULE_HEADER = """/**
 * Generated by QAgent from the discovered API surface.
 *
 * Do not edit by hand: regenerate with `qagent emit --framework jest`. These
 * tests need only Jest and Node 18+ (built-in fetch), so they keep working if
 * QAgent is uninstalled.
 *
 * Point them at a running application with QAGENT_BASE_URL, and supply auth
 * with QAGENT_AUTH_HEADER (for example "Authorization: Bearer ...").
 */

const BASE_URL = (process.env.QAGENT_BASE_URL || {base_url}).replace(/\\/+$/, "");
const TIMEOUT_MS = Number(process.env.QAGENT_TIMEOUT || "30") * 1000;

jest.setTimeout(TIMEOUT_MS + 5000);

function authHeaders() {{
  const raw = process.env.QAGENT_AUTH_HEADER || "";
  const index = raw.indexOf(":");
  if (index < 0) return {{}};
  return {{ [raw.slice(0, index).trim()]: raw.slice(index + 1).trim() }};
}}

async function send(method, path, pathParams, query, body, headers, authed) {{
  for (const [name, value] of Object.entries(pathParams || {{}})) {{
    path = path.split("{{" + name + "}}").join(encodeURIComponent(String(value)));
  }}
  const url = new URL(BASE_URL + path);
  for (const [name, value] of Object.entries(query || {{}})) {{
    url.searchParams.set(name, String(value));
  }}
  const sent = {{ ...(headers || {{}}), ...(authed ? authHeaders() : {{}}) }};
  if (body !== null && body !== undefined) sent["content-type"] = "application/json";
  const started = Date.now();
  const response = await fetch(url, {{
    method,
    headers: sent,
    body: body === null || body === undefined ? undefined : JSON.stringify(body),
    signal: AbortSignal.timeout(TIMEOUT_MS),
  }});
  const text = await response.text();
  let json;
  try {{
    json = JSON.parse(text);
  }} catch {{
    json = undefined;
  }}
  return {{
    status: response.status,
    headers: response.headers,
    text,
    json,
    elapsedMs: Date.now() - started,
  }};
}}
"""

_JSON_PATH_HELPER = """
/** Walk a dotted path, mirroring the runner's own resolution. */
function jsonPath(payload, path) {
  let current = payload;
  for (const part of String(path).split(".")) {
    if (current && typeof current === "object" && !Array.isArray(current) && part in current) {
      current = current[part];
    } else if (Array.isArray(current) && /^\\d+$/.test(part) && Number(part) < current.length) {
      current = current[Number(part)];
    } else {
      return [false, undefined];
    }
  }
  return [true, current];
}
"""

#: Port of modules/graphql/errors.py. Kept in step by test_jest_emitter.py.
_GRAPHQL_HELPERS = r"""
const INTERNAL_CODES = new Set(["INTERNAL_SERVER_ERROR", "INTERNAL_ERROR", "INTERNAL"]);

const RAW_EXCEPTION = new RegExp(
  "(invalid literal for int\\(\\)" +
    "|'NoneType' object" +
    "|object is not (subscriptable|iterable|callable)" +
    "|object has no attribute" +
    "|can only join an iterable" +
    "|list index out of range" +
    "|\\b(KeyError|TypeError|ValueError|AttributeError|ZeroDivisionError)\\b" +
    "|Cannot read propert(y|ies) of (undefined|null)" +
    "|is not a function" +
    "|undefined is not an object" +
    "|NullPointerException" +
    "|nil pointer dereference" +
    "|Traceback \\(most recent call last\\))",
  "i",
);

const CLIENT_HINT = new RegExp(
  "(not found|does not exist|no such|invalid|must be|must not|required" +
    "|unauthori[sz]ed|unauthenticated|forbidden|permission|not allowed|expected)",
  "i",
);

function isPlainObject(value) {
  return value !== null && typeof value === "object" && !Array.isArray(value);
}

/** Python truthiness: [] and {} are false there, true here. */
function pyTruthy(value) {
  if (Array.isArray(value)) return value.length > 0;
  if (isPlainObject(value)) return Object.keys(value).length > 0;
  return Boolean(value);
}

function errorKind(error) {
  if (!isPlainObject(error)) return "unclear";
  const extensions = isPlainObject(error.extensions) ? error.extensions : {};
  const code = pyTruthy(extensions.code) ? extensions.code : error.type;
  const message = pyTruthy(error.message) ? String(error.message) : "";

  if (typeof code === "string" && INTERNAL_CODES.has(code.toUpperCase())) return "internal";
  if (pyTruthy(extensions.exception) || pyTruthy(extensions.stacktrace)) return "internal";
  if (RAW_EXCEPTION.test(message)) return "internal";
  if (typeof code === "string" && code) return "handled";
  if (CLIENT_HINT.test(message)) return "handled";
  return "unclear";
}

function graphqlFieldDenied(status, body, field) {
  if (status === 401 || status === 403) return true;
  if (!isPlainObject(body)) return true;
  if (!isPlainObject(body.data)) return true;
  return body.data[field] === null || body.data[field] === undefined;
}

function graphqlErrorKind(body) {
  if (!isPlainObject(body)) return "unclear";
  const errors = body.errors;
  if (!pyTruthy(errors)) return "none";
  if (!Array.isArray(errors)) return "unclear";
  const kinds = new Set(errors.map(errorKind));
  if (kinds.has("internal")) return "internal";
  if (kinds.size === 1 && kinds.has("handled")) return "handled";
  return "unclear";
}
"""


def graphql_helpers_source() -> str:
    """The JavaScript port on its own, for the parity test to execute."""
    return _GRAPHQL_HELPERS


def _assertion_lines(assertion: dict) -> list[str]:
    """One declarative assertion as Jest. Unknown types fail loudly, never pass."""
    kind = assertion.get("type", "unknown")
    value = assertion.get("value")

    if kind == "status_in":
        return [f"    expect({_js(list(value or []))}).toContain(response.status);"]
    if kind == "status_not_in":
        return [f"    expect({_js(list(value or []))}).not.toContain(response.status);"]
    if kind == "body_matches":
        return [f"    expect(response.text).toMatch(new RegExp({_js(str(value))}, \"i\"));"]
    if kind == "body_not_matches":
        return [f"    expect(response.text).not.toMatch(new RegExp({_js(str(value))}, \"i\"));"]
    if kind == "header_present":
        return [f"    expect(response.headers.has({_js(str(value).lower())})).toBe(true);"]
    if kind == "latency_under_ms":
        return [f"    expect(response.elapsedMs).toBeLessThanOrEqual({_js(value)});"]
    if kind == "json_path_exists":
        return [f"    expect(jsonPath(response.json, {_js(str(value))})[0]).toBe(true);"]
    if kind == "json_path_equals":
        path = str(assertion.get("path", ""))
        return [
            "    {",
            f"      const [found, actual] = jsonPath(response.json, {_js(path)});",
            "      expect(found).toBe(true);",
            f"      expect(actual).toEqual({_js(value)});",
            "    }",
        ]
    if kind == "graphql_error_kind_in":
        return [f"    expect({_js(list(value or []))}).toContain(graphqlErrorKind(response.json));"]
    if kind == "graphql_field_denied":
        return [
            "    expect(",
            f"      graphqlFieldDenied(response.status, response.json, {_js(str(value))}),",
            "    ).toBe(true);",
        ]
    return [f"    throw new Error({_js(f'QAgent could not render assertion type {kind!r}')});"]


def render_case(case: GeneratedCase) -> str:
    spec = case.spec or {}
    request = spec.get("request") or {}
    assertions = spec.get("assertions") or []

    lines = [f"  test({_js(case.name)}, async () => {{"]
    if case.rationale:
        lines.append(f"    // {_js(case.rationale)[1:-1]}")
    if spec.get("expectation"):
        lines.append(f"    // Expect: {_js(str(spec['expectation']))[1:-1]}")
    lines += [
        "    const response = await send(",
        f"      {_js(str(request.get('method', 'GET')).upper())},",
        f"      {_js(str(request.get('path', '/')))},",
        f"      {_js(dict(request.get('path_params') or {}))},",
        f"      {_js(dict(request.get('query') or {}))},",
        f"      {_js(request.get('json'))},",
        f"      {_js(dict(request.get('headers') or {}))},",
        f"      {_js(str(request.get('auth', 'default')) != 'none')},",
        "    );",
    ]
    for assertion in assertions:
        lines.extend(_assertion_lines(assertion))
    if not assertions:
        lines.append("    expect(response.status).toBeLessThan(500);")
    lines.append("  });")
    return "\n".join(lines) + "\n"


def emit(
    cases: list[GeneratedCase], *, base_url: str, out_dir: Path, dry_run: bool = False
) -> EmissionReport:
    """Write one ``<module>.test.js`` per API module. Same report as pytest's."""
    report = EmissionReport()
    if not cases:
        report.skipped.append("no cases to emit")
        return report

    grouped: dict[str, list[GeneratedCase]] = {}
    for case in cases:
        grouped.setdefault(module_name_for(case), []).append(case)

    for module, module_cases in sorted(grouped.items()):
        types = {
            a.get("type")
            for c in module_cases
            for a in (c.spec or {}).get("assertions") or []
        }
        content = _MODULE_HEADER.format(base_url=_js(base_url))
        if types & {"json_path_exists", "json_path_equals"}:
            content += _JSON_PATH_HELPER
        if types & {"graphql_error_kind_in", "graphql_field_denied"}:
            content += _GRAPHQL_HELPERS
        content += f"\ndescribe({_js(module)}, () => {{\n"
        content += "\n".join(render_case(c) for c in module_cases)
        content += "});\n"

        file_path = f"{module}.test.js"
        report.files.append(
            EmittedFile(path=file_path, content=content, case_count=len(module_cases))
        )
        if not dry_run:
            target = out_dir / file_path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")

    logger.info(
        "emitted %d Jest case(s) across %d file(s)%s",
        report.case_count,
        len(report.files),
        " (dry run)" if dry_run else "",
    )
    return report
